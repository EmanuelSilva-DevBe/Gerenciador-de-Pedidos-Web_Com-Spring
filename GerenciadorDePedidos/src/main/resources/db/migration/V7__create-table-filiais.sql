-- V7: tabela filiais (entidade Filiais).

CREATE TABLE filiais (
    id         BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    nome       VARCHAR(255),
    cod_filial INTEGER      NOT NULL,  -- int primitivo no Java: nunca e null
    cidade     VARCHAR(255),
    ativa      BOOLEAN,
    CONSTRAINT filiais_pkey PRIMARY KEY (id),
    -- Espelha o @Min(1) da entidade: a regra vale tambem para INSERTs fora da aplicacao.
    CONSTRAINT filiais_cod_filial_check CHECK (cod_filial >= 1)
);
