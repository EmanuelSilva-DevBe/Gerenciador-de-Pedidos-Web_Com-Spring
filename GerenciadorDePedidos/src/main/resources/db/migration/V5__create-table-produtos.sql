-- V5: tabela produtos (entidade Produtos).
-- Nomes seguem a convencao do Spring Boot: camelCase -> snake_case (nomeProduto -> nome_produto).

CREATE TABLE produtos (
    id                BIGINT         GENERATED BY DEFAULT AS IDENTITY,
    nome_produto      VARCHAR(255),
    sku               VARCHAR(255),
    preco_produto     NUMERIC(38, 2) NOT NULL,
    descricao_produto VARCHAR(255)   DEFAULT 'Produto sem descricao',
    ativo             BOOLEAN        DEFAULT TRUE,
    categoria         VARCHAR(255),
    CONSTRAINT produtos_pkey PRIMARY KEY (id),
    -- Espelha o enum CategoriaDeProdutos: um valor novo no enum exige uma migration nova.
    CONSTRAINT produtos_categoria_check
        CHECK (categoria IN ('ACOUGUE', 'MERCEARIA', 'BEBIDAS', 'FITNESS'))
);
