-- V6: tabelas venda e venda_itens (entidades Venda e VendaItem).
-- Ordem importa: venda_itens referencia venda e produtos (V5), entao vem por ultimo.

CREATE TABLE venda (
    -- O Hibernate ja gera o UUID (GenerationType.UUID); o DEFAULT cobre INSERTs manuais.
    id_venda            UUID           NOT NULL DEFAULT gen_random_uuid(),
    valor_total_davenda NUMERIC(38, 2),
    CONSTRAINT venda_pkey PRIMARY KEY (id_venda)
);

-- Colunas de FK com o nome que o Hibernate espera: <atributo>_<pk referenciada>
--   idProdutos -> id_produtos_id  |  idVenda -> id_venda_id_venda
CREATE TABLE venda_itens (
    id                BIGINT         GENERATED BY DEFAULT AS IDENTITY,
    preco_unitario    NUMERIC(38, 2),
    quantidade        INTEGER        NOT NULL,
    id_produtos_id    BIGINT,
    id_venda_id_venda UUID,
    CONSTRAINT venda_itens_pkey PRIMARY KEY (id),
    CONSTRAINT venda_itens_produto_fk FOREIGN KEY (id_produtos_id)    REFERENCES produtos (id),
    CONSTRAINT venda_itens_venda_fk   FOREIGN KEY (id_venda_id_venda) REFERENCES venda (id_venda)
);

-- O PostgreSQL NAO cria indice automatico para FK. Sem eles, buscar itens de uma venda
-- (ou validar exclusao de produto) vira full scan conforme a tabela cresce.
CREATE INDEX venda_itens_venda_idx   ON venda_itens (id_venda_id_venda);
CREATE INDEX venda_itens_produto_idx ON venda_itens (id_produtos_id);
