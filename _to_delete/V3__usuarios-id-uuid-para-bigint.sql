-- V3: troca o id de usuarios de UUID para BIGINT autoincremental (IDENTITY).
--
-- Por que uma V3 em vez de editar a V2?
--   A V2 ja foi aplicada e o Flyway guarda o checksum dela. Editar a V2 quebra a
--   validacao em todo banco onde ela ja rodou. Migration aplicada e imutavel: corrige-se para frente.
--
-- Por que nao um ALTER COLUMN ... TYPE BIGINT?
--   Nao existe conversao de UUID para BIGINT. Entao criamos uma coluna nova,
--   o PostgreSQL numera as linhas existentes, e trocamos a antiga pela nova.
--
-- Atencao: usuarios existentes recebem ids novos (1, 2, 3...). Hoje nenhuma tabela
-- referencia usuarios.id; se passar a referenciar antes de rodar, esta migration precisa mudar.

-- 1. Nova coluna IDENTITY: as linhas existentes ja recebem valores da sequencia.
ALTER TABLE usuarios
    ADD COLUMN id_novo BIGINT GENERATED BY DEFAULT AS IDENTITY;

-- 2. Remove o id UUID (a PK sai junto, pois depende dessa coluna).
ALTER TABLE usuarios DROP COLUMN id;

-- 3. Coloca a nova coluna no lugar e recria a PK.
ALTER TABLE usuarios RENAME COLUMN id_novo TO id;
ALTER TABLE usuarios ADD CONSTRAINT usuarios_pkey PRIMARY KEY (id);
